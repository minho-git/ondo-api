-- ═══════════════════════════════════════════════════════════════
--  MUL-68 · 서류 파일 컬럼 이름 정정 (file_url → file_key)
--
--  왜   이 컬럼에 들어가는 값은 URL 이 아니라 저장소 키다.
--         저장 O   uploads/2026/09/ab12cd34.jpg
--         저장 X   https://cdn.ddmondo.co.kr/uploads/2026/09/ab12cd34.jpg
--
--       키로 저장하면 도메인·버킷·CDN 이 바뀌어도 쌓인 행을 손대지 않아도 되고,
--       사업자등록증·대표자신분증처럼 개인정보인 파일을 나중에 비공개 버킷 +
--       서명 URL 로 옮길 때 설정만 바꾸면 된다. 절대 URL 로 굳혀두면
--       그 전환에 전 행 백필이 따라붙는다.
--
--       V1 이 지은 이름은 file_url 이었다. 이름과 내용이 다른 컬럼은 주석을 아무리
--       달아도 다음 사람이 컬럼명을 먼저 믿는다. 참조하는 코드도 데이터도 아직
--       없는 지금이 고치기 가장 싸다.
--
--  주의 RENAME 은 이름만 바꾼다. varchar(500) 과 NOT NULL 은 그대로다.
--       (DROP + ADD 로 하면 둘 다 조용히 사라진다)
--
--       팀원 ERD(ondo_erd_v260823_1524.mermaid)의 표기와 달라진다.
--       소매의 retailer_doc.file_url 은 별개 DB·별개 티켓이라 건드리지 않았다.
-- ═══════════════════════════════════════════════════════════════

ALTER TABLE wholesale.wholesaler_document
    RENAME COLUMN file_url TO file_key;
