--  MUL-68 · 이메일 소문자 강제
--
--  왜   티켓이 "이메일 소문자 정규화 저장 (로그인도 동일 정규화)" 를 요구한다.
--       정규화는 앱이 하지만(Locale.ROOT), 정규화를 빠뜨린 경로가 하나라도 생기면
--       — 로그인(MUL-69) · 재신청(MUL-71) 처럼 진입점은 계속 늘어난다 —
--       대소문자만 다른 중복 계정이 조용히 생긴다.
--       wholesaler_email_uk 는 대소문자를 구분하므로 그걸 막지 못한다.
--
--  무엇 DB 가 정규화를 대신 해주지는 않는다. 앱이 안 했을 때 INSERT 가 실패해서
--       버그가 즉시 드러나게 하는 장치다. 조용한 중복 계정보다 시끄러운 실패가 낫다.
--
--  대안으로 citext 확장이나 lower(email) 함수 인덱스도 있었다. CHECK 를 고른 이유는
--       확장 설치·인덱스 재생성 없이 한 줄이고, UK 는 이미 email 컬럼에 있기 때문이다.
-- ═══════════════════════════════════════════════════════════════

ALTER TABLE wholesale.wholesaler
    ADD CONSTRAINT wholesaler_email_lower_ck CHECK (email = lower(email));
